// Purpose: Export the WebSocket RPC surface for the native (Rust) client.
//
// Walks the feature RPC group the server mounts on `/ws` and writes:
//   - `rpc-manifest.json`: one entry per RPC (tag, stream flag, schema identifiers)
//   - `rpc_manifest.rs`:   the same manifest as Rust constants for `synara-protocol`
//
// Usage: bun packages/contracts/scripts/export-rpc-manifest.ts <out-dir>
// The native drift gate regenerates these files and fails on any diff.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { RpcSchema } from "effect/unstable/rpc";

import { WsFeatureRpcGroup } from "../src/rpc";
import {
  WS_CLIENT_REQUIRED_CAPABILITIES,
  WS_PROTOCOL_EPOCH,
  WS_PROTOCOL_MAX_REVISION,
  WS_PROTOCOL_MIN_REVISION,
  WS_STREAM_LIMITS,
} from "../src/wsCompatibility";

interface ManifestEntry {
  readonly tag: string;
  readonly stream: boolean;
}

const entries: ManifestEntry[] = [];
for (const [tag, rpc] of WsFeatureRpcGroup.requests) {
  entries.push({ tag, stream: RpcSchema.isStreamSchema(rpc.successSchema) });
}
entries.sort((a, b) => a.tag.localeCompare(b.tag));

const manifest = {
  protocolEpoch: WS_PROTOCOL_EPOCH,
  minRevision: WS_PROTOCOL_MIN_REVISION,
  maxRevision: WS_PROTOCOL_MAX_REVISION,
  requiredCapabilities: [...WS_CLIENT_REQUIRED_CAPABILITIES],
  streamLimits: WS_STREAM_LIMITS,
  rpcs: entries,
};

const constName = (tag: string): string =>
  tag
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .toUpperCase();

const rust = [
  "// @generated by packages/contracts/scripts/export-rpc-manifest.ts. Do not edit.",
  "",
  "/// One RPC the server mounts on `/ws`.",
  "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
  "pub struct RpcInfo {",
  "    pub tag: &'static str,",
  "    pub stream: bool,",
  "}",
  "",
  `pub const PROTOCOL_EPOCH: u32 = ${WS_PROTOCOL_EPOCH};`,
  `pub const MIN_REVISION: u32 = ${WS_PROTOCOL_MIN_REVISION};`,
  `pub const MAX_REVISION: u32 = ${WS_PROTOCOL_MAX_REVISION};`,
  `pub const STREAM_LIMIT_TOTAL: usize = ${WS_STREAM_LIMITS.totalPerClient};`,
  `pub const STREAM_LIMIT_THREAD: usize = ${WS_STREAM_LIMITS.threadPerClient};`,
  "",
  "pub const REQUIRED_CAPABILITIES: &[&str] = &[",
  ...WS_CLIENT_REQUIRED_CAPABILITIES.map((capability) => `    ${JSON.stringify(capability)},`),
  "];",
  "",
  "pub mod tags {",
  ...entries.map((entry) => `    pub const ${constName(entry.tag)}: &str = ${JSON.stringify(entry.tag)};`),
  "}",
  "",
  "pub const RPCS: &[RpcInfo] = &[",
  ...entries.map(
    (entry) => `    RpcInfo { tag: ${JSON.stringify(entry.tag)}, stream: ${entry.stream} },`,
  ),
  "];",
  "",
].join("\n");

const outDir = process.argv[2];
if (!outDir) {
  console.error("usage: export-rpc-manifest.ts <out-dir>");
  process.exit(2);
}
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "rpc-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
writeFileSync(join(outDir, "rpc_manifest.rs"), rust);
console.log(`exported ${entries.length} RPCs (${entries.filter((e) => e.stream).length} streams)`);
